function esc(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  const s = String(v).replace(/'/g, "''");
  return `'${s}'`;
}

function isDisclosed(v) {
  if (!v) return false;
  const s = String(v).trim();
  if (!s) return false;
  if (/^undisclosed$/i.test(s)) return false;
  return true;
}

